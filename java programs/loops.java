public class loops {
    public static void main(String[] args) {
        // System.out.println("shamshuddin");
        // System.out.println("shamshuddin");

        // for loop
        for(int i = 0; i<=3; i++){
            System.out.println("Shamshuddin");
        }
        // print 100 - 1 
        for(int i = 100; i>=1; i--){
            System.out.println(i);
        }
        //while loop
        int i = 10;
        while (i>=1) { 
            System.out.println(i);
            i--;
        }
    }
}