public class Constants{
    public static void main(String[] args){
        int age =18;
        age = 19;
        age = 20;
        System.out.println(age);

        final float pi = 3.14F;
        // pi = 1.1345F; we can't change the value of pi for that values we use "fianl" keyword for fixed values and constants
        System.out.println(pi);
    }
    
}
